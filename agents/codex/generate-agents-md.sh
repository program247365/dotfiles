#!/usr/bin/env bash
#
# Generate ~/.codex/AGENTS.md, Codex's global instructions.
#
# Claude Code reads ~/.claude/CLAUDE.md, which @imports the philosophy, plus
# ~/.claude/rules/*.md. Codex has neither @imports nor a rules directory, so
# it gets one file concatenated from the same sources pi's shared-rules
# extension reads. tool-use.md names Claude Code tools (Grep, Glob, Task)
# that Codex doesn't have.
#
# Run by agents/codex/install.sh (so every `dot`) and the 2026-10-19
# migration. Run it by hand after editing those sources.
# Idempotent: safe to re-run.

set -euo pipefail

DOTFILES_ROOT="${HOME}/.dotfiles"
CODEX_AGENTS_MD="${HOME}/.codex/AGENTS.md"
MARKER_PREFIX="<!-- Generated by ~/.dotfiles/agents/codex/"
MARKER="${MARKER_PREFIX}generate-agents-md.sh. Edit the sources, not this file. -->"

build() {
  echo "${MARKER}"
  for file in \
    "${DOTFILES_ROOT}/agents/claude/home/CLAUDE.md" \
    "${DOTFILES_ROOT}/agents/philosophy/SOFTWARE_ENGINEERING.md" \
    "${DOTFILES_ROOT}"/agents/claude/rules/*.md; do
    [ "$(basename "${file}")" = "tool-use.md" ] && continue
    echo ""
    cat "${file}"
  done
}

mkdir -p "$(dirname "${CODEX_AGENTS_MD}")"

# A hand-written file (no marker) is kept as a backup, never overwritten.
if [ -f "${CODEX_AGENTS_MD}" ] && [ ! -L "${CODEX_AGENTS_MD}" ]; then
  case "$(head -1 "${CODEX_AGENTS_MD}")" in
    "${MARKER_PREFIX}"*) ;;
    *)
      backup="${CODEX_AGENTS_MD}.bak.$(date +%Y%m%d%H%M%S)"
      mv "${CODEX_AGENTS_MD}" "${backup}"
      echo "  Backed up existing ~/.codex/AGENTS.md to ${backup}"
      ;;
  esac
fi

# rm first: older installs left a symlink here, and > would write through it.
rm -f "${CODEX_AGENTS_MD}"
build > "${CODEX_AGENTS_MD}"
echo "  Generated ~/.codex/AGENTS.md"
